/* Generates the Glass design mode's bundled landscape scenes as SVG.
 * Output: src/newtab/scenes/{dusk,night,dawn}.svg
 * Deterministic (seeded) so regenerating produces identical files.
 * Usage: node scripts/generate-scenes.mjs */
import { writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const out = fileURLToPath(new URL('../src/newtab/scenes/', import.meta.url));
const W = 1600, H = 1000;

function rng(seed) {
  let s = seed >>> 0;
  return () => { s = (s * 1664525 + 1013904223) >>> 0; return s / 2 ** 32; };
}

/** Midpoint-displacement ridge, returned as a smooth closed SVG path. */
function ridge(seed, base, amp, rough = .55, steps = 6) {
  const rand = rng(seed);
  let pts = [[-40, base + (rand() - .5) * amp], [W + 40, base + (rand() - .5) * amp]];
  let a = amp;
  for (let i = 0; i < steps; i++) {
    const next = [pts[0]];
    for (let j = 1; j < pts.length; j++) {
      const [x0, y0] = pts[j - 1], [x1, y1] = pts[j];
      next.push([(x0 + x1) / 2, (y0 + y1) / 2 + (rand() - .5) * a], [x1, y1]);
    }
    pts = next; a *= rough;
  }
  // Catmull-Rom → cubic Bézier for soft, photographic silhouettes.
  let d = `M${pts[0][0].toFixed(1)},${pts[0][1].toFixed(1)}`;
  for (let i = 0; i < pts.length - 1; i++) {
    const p0 = pts[i - 1] ?? pts[i], p1 = pts[i], p2 = pts[i + 1], p3 = pts[i + 2] ?? p2;
    const c1 = [p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6];
    const c2 = [p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6];
    d += `C${c1.map(n => n.toFixed(1))} ${c2.map(n => n.toFixed(1))} ${p2.map(n => n.toFixed(1))}`;
  }
  return `${d}L${W + 40},${H + 40}L-40,${H + 40}Z`;
}

function stars(seed, count, maxY) {
  const rand = rng(seed);
  let s = '';
  for (let i = 0; i < count; i++) {
    const r = rand() < .08 ? 1.6 : rand() * .9 + .35;
    s += `<circle cx="${(rand() * W).toFixed(0)}" cy="${(rand() ** 1.4 * maxY).toFixed(0)}" r="${r.toFixed(2)}" opacity="${(rand() * .6 + .25).toFixed(2)}"/>`;
  }
  return `<g fill="#fff">${s}</g>`;
}

/** Tiered pines, tallest toward the frame edge, for a sense of foreground. */
function trees(seed, side, color) {
  const rand = rng(seed);
  let s = '';
  for (let i = 0; i < 18; i++) {
    const t = rand();
    const edge = side === 'left' ? t * 240 - 30 : W - t * 260 + 30;
    const h = (1 - t) * 190 + 50 + rand() * 50, w = h * (.3 + rand() * .08), y = 930 - rand() * 25;
    let d = `M${edge.toFixed(0)},${(y - h).toFixed(0)}`;
    for (let k = 1; k <= 4; k++) {
      const ty = y - h + (h * k) / 4, tw = (w / 2) * (k / 4 + .25);
      d += `L${(edge + tw).toFixed(0)},${ty.toFixed(0)}L${(edge + tw * .45).toFixed(0)},${(ty - h * .06).toFixed(0)}`;
    }
    for (let k = 4; k >= 1; k--) {
      const ty = y - h + (h * k) / 4, tw = (w / 2) * (k / 4 + .25);
      d += `L${(edge - tw * .45).toFixed(0)},${(ty - h * .06).toFixed(0)}L${(edge - tw).toFixed(0)},${ty.toFixed(0)}`;
    }
    s += `<path d="${d.replace(/L([^L]*)$/, 'L$1')}Z"/>`;
  }
  return `<g fill="${color}" filter="url(#near)">${s}</g>`;
}

function scene({ name, sky, glow, cloud, layers, lake, shore, extra = '', vignette }) {
  const mountains = layers.map(([seed, base, amp, color, opacity = 1], i) =>
    `<path d="${ridge(seed, base, amp, .52)}" fill="${color}" opacity="${opacity}"${i < 2 ? ' filter="url(#mist)"' : ''}/>`).join('');
  const reflected = layers.slice(0, 2).map(([seed, base, amp, color]) =>
    `<path d="${ridge(seed, base, amp)}" fill="${color}" opacity=".28" transform="translate(0 ${2 * lake.top}) scale(1 -1)"/>`).join('');
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" preserveAspectRatio="xMidYMid slice">
<!-- TabFlow Glass scene: ${name}. Generated by scripts/generate-scenes.mjs. -->
<defs>
<linearGradient id="sky" x1="0" y1="0" x2="0" y2="1">${sky.map(([o, c]) => `<stop offset="${o}" stop-color="${c}"/>`).join('')}</linearGradient>
<radialGradient id="glow" cx="${glow.x / W}" cy="${glow.y / H}" r=".55"><stop offset="0" stop-color="${glow.color}" stop-opacity="${glow.opacity}"/><stop offset="1" stop-color="${glow.color}" stop-opacity="0"/></radialGradient>
<linearGradient id="lake" x1="0" y1="0" x2="0" y2="1">${lake.stops.map(([o, c]) => `<stop offset="${o}" stop-color="${c}"/>`).join('')}</linearGradient>
<linearGradient id="haze" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="${glow.color}" stop-opacity="0"/><stop offset=".7" stop-color="${glow.color}" stop-opacity=".22"/><stop offset="1" stop-color="${glow.color}" stop-opacity="0"/></linearGradient>
<radialGradient id="vig" cx=".5" cy=".45" r=".75"><stop offset=".55" stop-color="#000" stop-opacity="0"/><stop offset="1" stop-color="#000" stop-opacity="${vignette}"/></radialGradient>
<filter id="soft" x="-50%" y="-200%" width="200%" height="500%"><feGaussianBlur stdDeviation="28"/></filter>
<filter id="mist" x="-10%" y="-50%" width="120%" height="200%"><feGaussianBlur stdDeviation="3"/></filter>
<clipPath id="water"><rect y="${lake.top}" width="${W}" height="${H - lake.top}"/></clipPath>
<filter id="near" x="-10%" y="-10%" width="120%" height="120%"><feGaussianBlur stdDeviation="1.2"/></filter>
</defs>
<rect width="${W}" height="${H}" fill="url(#sky)"/>
${extra}
<rect width="${W}" height="${H}" fill="url(#glow)"/>
<g filter="url(#soft)" fill="${cloud.color}" opacity="${cloud.opacity}">
<ellipse cx="300" cy="230" rx="360" ry="46"/><ellipse cx="1180" cy="170" rx="420" ry="40"/><ellipse cx="820" cy="320" rx="300" ry="30"/><ellipse cx="1450" cy="380" rx="260" ry="26"/>
</g>
${mountains}
<rect y="${lake.top - 120}" width="${W}" height="170" fill="url(#haze)"/>
<rect y="${lake.top}" width="${W}" height="${H - lake.top}" fill="url(#lake)"/>
<g clip-path="url(#water)"><g filter="url(#mist)">${reflected}</g></g>
<ellipse cx="${glow.x}" cy="${lake.top + 70}" rx="46" ry="120" fill="${glow.color}" opacity="${lake.shine}" filter="url(#soft)"/>
<g stroke="${glow.color}" stroke-opacity="${lake.shine * .6}" stroke-width="1.4">${[0, 1, 2, 3, 4, 5].map(i => `<line x1="${glow.x - 120 + i * 17}" y1="${lake.top + 24 + i * 18}" x2="${glow.x + 40 + i * 15}" y2="${lake.top + 24 + i * 18}"/>`).join('')}</g>
<path d="${ridge(991, 905, 40, .45)}" fill="${shore}"/>
${trees(17, 'left', shore)}${trees(23, 'right', shore)}
<rect width="${W}" height="${H}" fill="url(#vig)"/>
</svg>
`;
}

